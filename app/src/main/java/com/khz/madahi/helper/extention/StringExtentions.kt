package com.khz.madahi.helper.extention

// ============================================================
// ابزارهای تمیزکاری متن قبل از ارسال به سرور
// ------------------------------------------------------------
// دیتابیس سرور utf8mb3 است (UTF-8 سه‌بایتی) که نمی‌تواند
// کاراکترهای ۴ بایتی (مثل ایموجی و برخی علائم خاص) را ذخیره
// کند. اگر این کاراکترها ارسال شوند، INSERT/UPDATE سرور با
// خطا می‌افتد و محتوا ذخیره نمی‌شود.
// ============================================================

/**
 * هر کاراکتر غیرمتنی ۴ بایتی (ایموجی، علائم خارج از BMP)
 * را از متن حذف می‌کند تا متن به‌درستی در سرور ذخیره شود.
 *
 * کاراکترهای ۴ بایتی در UTF-16 به‌صورت جفت‌سورروگات
 * (Surrogate Pair) با کد واحد 0xD800 تا 0xDFFF ذخیره می‌شوند؛
 * حذف هر دو نیمه یعنی حذف کامل کاراکتر.
 */
fun String.sanitizeForServer(): String = this.filter { it.code !in 0xD800..0xDFFF }

/**
 * sanitize + trim در یک قدم — برای اعتبارسنجی و ذخیره‌سازی.
 * (متنی که فقط ایموجی باشد بعد از این تابع خالی در نظر گرفته می‌شود)
 */
fun String.cleanForServer(): String = this.sanitizeForServer()
    .trim()
